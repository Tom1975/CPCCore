print("font:")
for c in range(32, 91):
    rows = [r for r in G.get(chr(c), "").split('|') if r] if G.get(chr(c)) else []
    data = []
    for y in range(8):
        r = rows[y] if y < len(rows) else "....."
        b = 0
        for x, ch in enumerate(r):
            if ch == '#': b |= 0x40 >> x     # columns 1 to 5 of the cell
        data.append(b)
    print("   db " + ",".join("#%02X" % v for v in data) + "   ; " + repr(chr(c)))
